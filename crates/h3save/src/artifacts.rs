/// One artifact slot in a hero record.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]
pub struct ArtifactEntry {
    pub artifact: Artifact,
    /// Spell ID if the artifact is a spell scroll, otherwise `u32::MAX`.
    pub scroll_spell_id: u32,
}

impl Default for ArtifactEntry {
    fn default() -> Self {
        ArtifactEntry {
            artifact: Artifact::NONE,
            scroll_spell_id: u32::MAX,
        }
    }
}

impl ArtifactEntry {
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.artifact == Artifact::NONE
    }
}
